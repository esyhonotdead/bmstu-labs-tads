def run_test(name, input_data, expected_code, expected_line):
    try:
        result = subprocess.run(
            [str(PROGRAM)],
            input=input_data,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            cwd=PROJECT_DIR,
            timeout=TIMEOUT,
        )
    except (OSError, subprocess.TimeoutExpired) as error:
        print(f"FAIL {name}: {error}")
        return False

    lines = result.stdout.splitlines()
    actual_line = lines[-1] if lines else ""
    passed = result.returncode == expected_code and actual_line == expected_line
    passed = passed and not result.stderr
    print(f"{'PASS' if passed else 'FAIL'} {name}")
    if not passed:
        print(f"  stdin: {input_data!r}")
        print(f"  Ожидалось: код {expected_code}, строка {expected_line!r}")
        print(f"  Получено:  код {result.returncode}, строка {actual_line!r}")
        print(f"  stdout: {result.stdout!r}")
        print(f"  stderr: {result.stderr!r}")
    return passed


def main():
    try:
        subprocess.run(["make", "all"], cwd=PROJECT_DIR, check=True, timeout=60)
    except (OSError, subprocess.SubprocessError) as error:
        print(f"Не удалось собрать программу: {error}", file=sys.stderr)
        return 1

    passed = 0
    for number, (description, data, code) in enumerate(NEGATIVE_TESTS, 1):
        passed += run_test(
            f"Негативный {number:02}: {description}", data, code, ERROR_MESSAGES[code]
        )
    for number, (description, integer, real, answer) in enumerate(POSITIVE_TESTS, 1):
        passed += run_test(
            f"Позитивный {number:02}: {description}",
            f"{integer}\n{real}\n",
            0,
            f"Результат: {answer}",
        )

    total = len(NEGATIVE_TESTS) + len(POSITIVE_TESTS)
    print(f"\nПройдено: {passed}/{total}. Не пройдено: {total - passed}.")
    return 0 if passed == total else 1


if __name__ == "__main__":
    sys.exit(main())
